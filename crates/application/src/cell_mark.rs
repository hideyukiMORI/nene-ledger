//! セルの見え方の印。

/// セルの見え方の印。見出しの行のセルと、本体のセルの選択の状態。カーソルのセルも選択に入る。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum CellMark {
    /// 固定した見出しの行のセル（選ばない）。
    Header,
    /// 固定した見出しの行の、選んだ列のセル（位置の手がかりに選択の色で塗る）。
    SelectedHeader,
    /// 本体の、選択の外のセル。
    Unselected,
    /// 本体の、選択の外で、選んだ範囲と同じ行か列のセル（薄い帯）。
    Band,
    /// 本体の、選択の中のセル。
    Selected,
    /// 本体の、カーソルのセル（選択の中で、枠を描く）。
    Cursor,
}
