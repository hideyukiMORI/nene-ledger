//! パレットの欄の短い知らせの種類（色を分ける・GitHub Issue #305）。

/// パレットの欄の短い知らせの種類。橙（強調）はフォーカスと確かめ、緑は済んだこと、赤は注意と誤り（専門家ペルソナの
/// 指摘「橙が確かめ・注意・完了・0 件のすべてに使われている」・#285）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NoteTone {
    /// 確かめ・進み具合・知らせ（強調の色）。
    Prompt,
    /// 済んだこと（緑）。
    Done,
    /// 注意と誤り（赤）。
    Problem,
}
