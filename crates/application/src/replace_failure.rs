//! 置き換えの失敗の種類（ADR 0025 の決定 3）。

/// 置き換えの失敗。どれでも、原本が元の名前で残っているかを種類で区別する。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReplaceFailure {
    /// ほかのアプリが原本を開いている（Windows の共有違反・ロックの違反）。再試行の後でも解けなかった。
    /// 原本は元のまま。一時ファイルも残っている。
    Locked,
    /// 権限が無い。原本は元のまま。一時ファイルも残っている。
    Denied,
    /// 置き換えが途中で止まった（Windows の 1176・1177）。🔴 元の名前に何があるかは分からない。一時ファイルを消さない。
    Interrupted,
    /// そのほかの失敗。原本は元のまま。一時ファイルも残っている。
    Other,
}
