//! 決まった間隔で画面のスレッドを起こす時計の口（port）。

/// 決まった間隔（50ms）で画面のスレッドを起こす時計の口（port・ADR 0014 の決定 3 と同じく、起こすだけで状態は渡さない）。
///
/// 中核は時刻を読まない（ARC-007）。時計の実装は OS のアダプタが持ち、刻みの数だけを数えて渡す。
/// 溝を押し続けたときの繰り返し（Issue #44）とドラッグの自動スクロール（Issue #45）に使う。
pub trait Ticker: core::fmt::Debug {
    /// 刻み始める（刻んでいれば何もしない）。
    fn start(&self);
    /// 止める（止まっていれば何もしない）。数えた刻みは捨てる。
    fn stop(&self);
    /// 前に受け取ってから刻んだ数を受け取る。
    fn take(&self) -> u64;
}
