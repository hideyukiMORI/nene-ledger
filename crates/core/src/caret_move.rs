//! 編集の欄の中でのカーソルの動かし方（ADR 0026 の決定 2）。

/// 編集の欄の中でカーソルを動かす向き。閉じた集合。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CaretMove {
    /// 1 字左へ。選択があって広げないなら、選択の始まりへ畳む。
    Left,
    /// 1 字右へ。選択があって広げないなら、選択の終わりへ畳む。
    Right,
    /// 今の行の先頭へ。
    Home,
    /// 今の行の末尾へ。
    End,
    /// 上の行の同じ桁へ。最初の行からは先頭へ。
    Up,
    /// 下の行の同じ桁へ。最後の行からは末尾へ。
    Down,
}
