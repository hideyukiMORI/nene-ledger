/// 色の相対輝度（`SCALE` 倍）。`0.2126 R + 0.7152 G + 0.0722 B`。
#[must_use]
pub fn luminance(color: Color) -> u64 {
    let linear = |value: u8| u64::from(LINEAR.get(usize::from(value)).copied().unwrap_or(0));
    (2126 * linear(color.red()) + 7152 * linear(color.green()) + 722 * linear(color.blue()))
        / 10_000
}

/// 2 つの色のコントラスト比が `ratio_tenths / 10` 以上か（4.5 なら 45、3.0 なら 30）。
#[must_use]
pub fn meets(first: Color, second: Color, ratio_tenths: u64) -> bool {
    let (a, b) = (luminance(first), luminance(second));
    let (light, dark) = (a.max(b), a.min(b));
    // (light + 0.05) / (dark + 0.05) >= ratio を、両辺に 10 と SCALE を掛けて整数で比べる。
    let offset = SCALE / 20;
    (light + offset) * 10 >= ratio_tenths * (dark + offset)
}

/// コントラスト比の 100 倍（切り捨て）。記録と試しのため。
#[must_use]
pub fn ratio_hundredths(first: Color, second: Color) -> u64 {
    let (a, b) = (luminance(first), luminance(second));
    let offset = SCALE / 20;
    (a.max(b) + offset) * 100 / (a.min(b) + offset)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn black_and_white_are_twenty_one_to_one() {
        let (black, white) = (Color::new(0, 0, 0), Color::new(0xFF, 0xFF, 0xFF));
        assert_eq!(luminance(black), 0);
        assert_eq!(luminance(white), SCALE);
        assert_eq!(ratio_hundredths(black, white), 2100);
        assert!(meets(black, white, 210));
    }

    #[test]
    fn known_pairs_match_the_published_ratios() {
        // #767676 は白の上でちょうど 4.5 を超える灰色として知られる（4.54）。#777777 は届かない（4.48）。
        let white = Color::new(0xFF, 0xFF, 0xFF);
        assert!(meets(Color::new(0x76, 0x76, 0x76), white, 45));
        assert!(!meets(Color::new(0x77, 0x77, 0x77), white, 45));
        assert_eq!(ratio_hundredths(Color::new(0x76, 0x76, 0x76), white), 454);
        // 順は問わない。
        assert!(meets(white, Color::new(0x59, 0x63, 0x6E), 45));
    }
}
